s = input()

lst = s.split()
d = {"Шшшшшш": ["Вампир", 10], "Аууууу": ["Вурдалак", 13], "Рррррр": ["Оборотень", 8], "Уууууу": ["Призрак", 14], "Гррррр": ["Демон", 21]}
c = 0

for i in lst:
    if i in d:
        m = d[i][0]
        h = d[i][1]
        print(f"Монстр пойман! Это {m}! Битва начинается!")
        break

while h > 0:
    h = max(0, h - 2)
    n = "Дон" if c % 2 == 0 else "Сим"
    print(f"Ход {n}а: {m} получает 2 урона! У {m} осталось {h} жизней.")
    c += 1
    if h <= 0:
        print(f"{m} убит!")
